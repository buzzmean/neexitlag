# Definitions only. Privileged image/boot operations call these explicitly.
function Set-ClubFileAcl([string]$Path,[string]$OwnerSid='', [switch]$Public){
 if((Get-Item -LiteralPath $Path -Force).Attributes -band [IO.FileAttributes]::ReparsePoint){throw 'CLUB_REPARSE_POINT_REJECTED'}
 $acl=[Security.AccessControl.FileSecurity]::new();$acl.SetAccessRuleProtection($true,$false);$acl.SetOwner([Security.Principal.SecurityIdentifier]::new('S-1-5-32-544'))
 foreach($sid in @('S-1-5-18','S-1-5-32-544')){$acl.AddAccessRule([Security.AccessControl.FileSystemAccessRule]::new([Security.Principal.SecurityIdentifier]::new($sid),'FullControl','Allow'))}
 if($Public){$acl.AddAccessRule([Security.AccessControl.FileSystemAccessRule]::new([Security.Principal.SecurityIdentifier]::new($OwnerSid),'Read','Allow'))}
 Set-Acl -LiteralPath $Path -AclObject $acl
}
function Write-ClubJson([string]$Path,$Value,[string]$OwnerSid='', [switch]$Public){
 $tmp=Join-Path (Split-Path $Path) ('.club-'+[Guid]::NewGuid().ToString('N'))
 try{
  [IO.File]::WriteAllText($tmp,($Value|ConvertTo-Json -Depth 8 -Compress),[Text.UTF8Encoding]::new($false));Set-ClubFileAcl $tmp
  if(Test-Path -LiteralPath $Path){if((Get-Item $Path -Force).Attributes -band [IO.FileAttributes]::ReparsePoint){throw 'CLUB_REPARSE_POINT_REJECTED'};[IO.File]::Replace($tmp,$Path,[NullString]::Value)}else{[IO.File]::Move($tmp,$Path)}
  Set-ClubFileAcl $Path -OwnerSid $OwnerSid -Public:$Public
 }finally{if(Test-Path $tmp){Remove-Item -LiteralPath $tmp -Force}}
}
function Assert-ClubImageClean([string]$Directory){
 foreach($name in @('identity.json','device.pem','probe.token','club-boot-ready.json')){if(Test-Path -LiteralPath (Join-Path $Directory $name)){throw 'CLUB_IMAGE_HAS_RUNTIME_STATE; use a clean activation-only image, existing state preserved'}}
 $pending=Join-Path $Directory 'state\activation-pending'
 if((Test-Path $pending) -and @(Get-ChildItem -LiteralPath $pending -Recurse -File -Filter identity.json).Count){throw 'CLUB_IMAGE_HAS_PENDING_PRIVATE_KEY; existing state preserved'}
}
function Get-ClubBrowserPaths {
 $rows=@();foreach($exe in @('chrome.exe','msedge.exe')){
  $candidates=@()
  foreach($hive in @('HKLM:\SOFTWARE','HKLM:\SOFTWARE\WOW6432Node','HKCU:\SOFTWARE')){
   $key=Get-Item -LiteralPath ($hive+'\Microsoft\Windows\CurrentVersion\App Paths\'+$exe) -ErrorAction SilentlyContinue
   if($key){$value=[string]$key.GetValue('');if($value){$candidates+=,$value.Trim('"')}}
  }
  if($exe -eq 'chrome.exe'){$relative='Google\Chrome\Application\chrome.exe'}else{$relative='Microsoft\Edge\Application\msedge.exe'}
  foreach($base in @($env:ProgramFiles,${env:ProgramFiles(x86)},$env:LOCALAPPDATA)){if($base){$candidates+=,(Join-Path $base $relative)}}
  foreach($path in $candidates){if(Test-Path -LiteralPath $path -PathType Leaf){$rows+=,(Get-Item -LiteralPath $path).FullName;break}}
 }
 return $rows
}

function Assert-ClubBootTaskOwnership([string]$Arguments){
 $task=Get-ScheduledTask -TaskName 'VELIQ Club Boot' -ErrorAction SilentlyContinue
 if($task -and (@($task.Actions).Count -ne 1 -or [string]$task.Actions[0].Execute -ine "$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe" -or [string]$task.Actions[0].Arguments -cne $Arguments -or [string]$task.Principal.UserId -notin @('SYSTEM','S-1-5-18'))){throw 'CLUB_FOREIGN_BOOT_TASK_PRESERVED'}
}

function Remove-OwnedClubBootTask {
 $task=Get-ScheduledTask -TaskName 'VELIQ Club Boot' -ErrorAction SilentlyContinue
 if(!$task){return}
 $boot=Join-Path $PSScriptRoot 'club-image-boot.ps1'
 # Exact script and arguments generated by our installer; no deletion of foreign tasks.
 $directory=Join-Path $env:ProgramData 'neexitlag'
 $args='-NoProfile -NonInteractive -WindowStyle Hidden -ExecutionPolicy Bypass -Command "& ' + "'"+$boot+"'"+' -InstallDirectory '+"'"+$directory+"'"+'"'
 Assert-ClubBootTaskOwnership $args
 Unregister-ScheduledTask -TaskName 'VELIQ Club Boot' -Confirm:$false
}
